    BATCH_ID,
    MANUFACTURING_SITE
FROM STAGING.AE_REPORT_CLEAN;

INSERT INTO CURATED.DIM_DATE
(
    REPORT_DATE,
    YEAR,
    MONTH,
    MONTH_NAME,
    QUARTER
)
SELECT DISTINCT
    TO_DATE(REPORT_RECEIVED_DATE, 'YYYY-MM-DD') AS REPORT_DATE,
    EXTRACT(YEAR FROM TO_DATE(REPORT_RECEIVED_DATE, 'YYYY-MM-DD')) AS YEAR,
    EXTRACT(MONTH FROM TO_DATE(REPORT_RECEIVED_DATE, 'YYYY-MM-DD')) AS MONTH,
    MONTHNAME(TO_DATE(REPORT_RECEIVED_DATE, 'YYYY-MM-DD')) AS MONTH_NAME,
    CONCAT('Q', EXTRACT(QUARTER FROM TO_DATE(REPORT_RECEIVED_DATE, 'YYYY-MM-DD'))) AS QUARTER
FROM STAGING.AE_REPORT_CLEAN
ORDER BY REPORT_DATE;

