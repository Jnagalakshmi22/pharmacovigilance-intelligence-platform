#Analytical Views
CREATE OR REPLACE VIEW CURATED.VW_AE_COUNTS_BY_DRUG_MONTH AS
SELECT
    DD.DRUG_NAME,
    DT.YEAR,
    DT.MONTH,
    COUNT(*) AS AE_REPORT_COUNT
FROM CURATED.FACT_AE_REPORT F
JOIN CURATED.DIM_DRUG DD
ON F.DRUG_KEY = DD.DRUG_KEY
JOIN CURATED.DIM_DATE DT
ON F.DATE_KEY = DT.DATE_KEY
GROUP BY
    DD.DRUG_NAME,
    DT.YEAR,
    DT.MONTH;

CREATE OR REPLACE VIEW CURATED.VW_SERIOUS_EVENT_RATE_BY_COUNTRY AS
SELECT
    DC.COUNTRY,
    COUNT(*) AS TOTAL_REPORTS,
    SUM(
        CASE
            WHEN F.EVENT_SERIOUSNESS='SERIOUS' THEN 1
            ELSE 0
        END
    ) AS SERIOUS_REPORTS,
    ROUND(
        100.0 *
        SUM(
            CASE
                WHEN F.EVENT_SERIOUSNESS='SERIOUS' THEN 1
                ELSE 0
            END
        ) / COUNT(*),
        2
    ) AS SERIOUS_EVENT_RATE_PERCENT
FROM CURATED.FACT_AE_REPORT F
JOIN CURATED.DIM_COUNTRY DC
ON F.COUNTRY_KEY = DC.COUNTRY_KEY
GROUP BY DC.COUNTRY;

#Batch Analytics Views
CREATE OR REPLACE VIEW CURATED.VW_AE_DRUG_BATCH_MONTHLY AS
SELECT
    D.DRUG_NAME,
    B.BATCH_ID,
    B.MANUFACTURING_SITE,
    DT.REPORT_DATE,
    COUNT(F.REPORT_ID) AS AE_REPORT_COUNT
FROM CURATED.FACT_AE_REPORT F
JOIN CURATED.DIM_DRUG D
    ON F.DRUG_KEY = D.DRUG_KEY
JOIN CURATED.DIM_BATCH B
    ON F.BATCH_KEY = B.BATCH_KEY
JOIN CURATED.DIM_DATE DT
    ON F.DATE_KEY = DT.DATE_KEY
GROUP BY
    D.DRUG_NAME,
    B.BATCH_ID,
    B.MANUFACTURING_SITE,
    DT.REPORT_DATE;

