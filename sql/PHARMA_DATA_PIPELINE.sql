#forecast

CREATE OR REPLACE VIEW CURATED.VW_AE_FORECAST_INPUT AS
SELECT
    MANUFACTURING_SITE,
    DATE_TRUNC('MONTH', REPORT_DATE) AS REPORT_MONTH,
    COUNT(*) AS AE_REPORT_COUNT
FROM CURATED.VW_AE_DRUG_BATCH_MONTHLY
GROUP BY
    MANUFACTURING_SITE,
    DATE_TRUNC('MONTH', REPORT_DATE);


CREATE OR REPLACE VIEW CURATED.VW_AE_FORECAST_INPUT_FINAL AS

WITH MONTHS AS (
    SELECT 
        DATEADD(
            MONTH,
            SEQ4(),
            '2025-01-01'
        ) AS REPORT_MONTH
    FROM TABLE(GENERATOR(ROWCOUNT => 12))
),

SITES AS (
    SELECT DISTINCT
        MANUFACTURING_SITE
    FROM CURATED.VW_AE_FORECAST_INPUT
)

SELECT
    S.MANUFACTURING_SITE,
    M.REPORT_MONTH,
    COALESCE(A.AE_REPORT_COUNT,0) AS AE_REPORT_COUNT
FROM SITES S
CROSS JOIN MONTHS M
LEFT JOIN CURATED.VW_AE_FORECAST_INPUT A
    ON S.MANUFACTURING_SITE = A.MANUFACTURING_SITE
    AND M.REPORT_MONTH = A.REPORT_MONTH;

SELECT *
FROM CURATED.VW_AE_FORECAST_INPUT_FINAL
ORDER BY MANUFACTURING_SITE, REPORT_MONTH;

